def add(a: int, b: int) -> int:
    return a + b


def difference(a: int, b: int) -> int:
    return a - b


def scale(a: int, b: int) -> int:
    return a * b


def halve(a: int) -> int:
    return a // 2


def remainder(a: int, b: int) -> int:
    return a % b


def negate(a: int) -> int:
    return -a
